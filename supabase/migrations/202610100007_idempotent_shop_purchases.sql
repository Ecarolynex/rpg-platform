-- Prevent a repeated checkout (for example after a lost HTTP response) from charging twice.
create table if not exists public.campanha_compras (
  id bigint generated by default as identity primary key,
  campanha_id uuid not null references public.campanhas(id) on delete cascade,
  personagem_id uuid not null references public.personagens(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  request_id uuid not null,
  itens jsonb not null check (jsonb_typeof(itens) = 'array'),
  saldo_po numeric not null,
  total_gasto numeric not null,
  created_at timestamptz not null default now(),
  unique (user_id, request_id)
);

alter table public.campanha_compras enable row level security;
grant select on public.campanha_compras to authenticated;
drop policy if exists "campanha_compras_select_membro" on public.campanha_compras;
create policy "campanha_compras_select_membro"
  on public.campanha_compras
  for select to authenticated
  using (
    exists (
      select 1 from public.campanha_membros membro
      where membro.campanha_id = campanha_compras.campanha_id
        and membro.user_id = auth.uid()
        and membro.status = 'ATIVO'
    )
  );

-- Replace the old two-argument function; its third argument below has a default
-- so existing app versions continue calling the RPC, while new clients send a key.
drop function if exists public.registrar_compra_carrinho(uuid, jsonb);
create function public.registrar_compra_carrinho(
  p_personagem_id uuid,
  p_itens jsonb,
  p_request_id uuid default gen_random_uuid()
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_usuario_id uuid := auth.uid();
  v_request_id uuid := coalesce(p_request_id, gen_random_uuid());
  v_dono_id uuid;
  v_campanha_id uuid;
  v_dados jsonb;
  v_carteira jsonb;
  v_saldo numeric;
  v_novo_saldo numeric;
  v_total numeric := 0;
  v_linha record;
  v_item_loja record;
  v_existing public.campanha_compras%rowtype;
begin
  if v_usuario_id is null then
    raise exception 'Usuário não autenticado.';
  end if;
  if jsonb_typeof(p_itens) is distinct from 'array' or jsonb_array_length(p_itens) = 0 then
    raise exception 'O carrinho está vazio.';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(v_usuario_id::text || ':' || v_request_id::text, 0));
  select * into v_existing
  from public.campanha_compras
  where user_id = v_usuario_id and request_id = v_request_id;
  if found then
    if v_existing.personagem_id <> p_personagem_id or v_existing.itens is distinct from p_itens then
      raise exception 'A chave de compra já foi usada com outros dados.';
    end if;
    return jsonb_build_object(
      'personagem_id', p_personagem_id,
      'saldo_po', v_existing.saldo_po,
      'total_gasto', v_existing.total_gasto
    );
  end if;

  select personagem.user_id, personagem.campanha_id, coalesce(personagem.dados, '{}'::jsonb)
    into v_dono_id, v_campanha_id, v_dados
  from public.personagens personagem
  where personagem.id = p_personagem_id
  for update;
  if not found then
    raise exception 'Personagem não encontrado.';
  end if;
  if v_campanha_id is null then
    raise exception 'O personagem não está vinculado a uma campanha.';
  end if;
  if not exists (
    select 1 from public.campanha_membros membro
    where membro.campanha_id = v_campanha_id
      and membro.user_id = v_usuario_id
      and membro.status = 'ATIVO'
  ) then
    raise exception 'Você não participa ativamente desta campanha.';
  end if;
  if v_dono_id <> v_usuario_id and not exists (
    select 1 from public.campanha_membros membro
    where membro.campanha_id = v_campanha_id
      and membro.user_id = v_usuario_id
      and membro.papel = 'MESTRE'
      and membro.status = 'ATIVO'
  ) then
    raise exception 'Você só pode comprar para seu personagem.';
  end if;

  v_carteira := case when jsonb_typeof(v_dados -> 'carteira') = 'object'
    then v_dados -> 'carteira' else '{}'::jsonb end;
  v_saldo := coalesce(nullif(v_carteira ->> 'po', '')::numeric, 0);

  for v_linha in
    select linha.loja_item_id, sum(linha.quantidade)::integer as quantidade
    from jsonb_to_recordset(p_itens) as linha(loja_item_id uuid, quantidade integer)
    group by linha.loja_item_id
    order by linha.loja_item_id
  loop
    if v_linha.loja_item_id is null or v_linha.quantidade is null or v_linha.quantidade <= 0 then
      raise exception 'O carrinho contém uma quantidade inválida.';
    end if;
    select loja_item.item_id, loja_item.preco_compra, loja_item.estoque,
      loja_item.ativo as item_ativo, loja.ativa, loja.campanha_id
      into v_item_loja
    from public.loja_itens loja_item
    join public.lojas loja on loja.id = loja_item.loja_id
    where loja_item.id = v_linha.loja_item_id
    for update of loja_item;
    if not found then
      raise exception 'Um dos itens não pertence a uma loja ativa.';
    end if;
    if v_item_loja.ativa is distinct from true
      or v_item_loja.item_ativo is distinct from true
      or v_item_loja.campanha_id <> v_campanha_id then
      raise exception 'O item não pertence à campanha do personagem.';
    end if;
    if v_item_loja.estoque < v_linha.quantidade then
      raise exception 'Estoque insuficiente para um dos itens.';
    end if;
    if v_item_loja.preco_compra < 0 then
      raise exception 'O preço do item é inválido.';
    end if;
    v_total := v_total + v_item_loja.preco_compra * v_linha.quantidade;
  end loop;

  if v_saldo < v_total then
    raise exception 'O personagem não tem ouro suficiente.';
  end if;

  for v_linha in
    select linha.loja_item_id, sum(linha.quantidade)::integer as quantidade
    from jsonb_to_recordset(p_itens) as linha(loja_item_id uuid, quantidade integer)
    group by linha.loja_item_id
    order by linha.loja_item_id
  loop
    select loja_item.item_id into v_item_loja
    from public.loja_itens loja_item
    where loja_item.id = v_linha.loja_item_id;

    update public.loja_itens
      set estoque = estoque - v_linha.quantidade
    where id = v_linha.loja_item_id and estoque >= v_linha.quantidade;
    if not found then
      raise exception 'O estoque mudou durante a compra. Tente novamente.';
    end if;

    update public.inventarios
      set quantidade = quantidade + v_linha.quantidade,
          updated_at = now()
    where personagem_id = p_personagem_id and item_id = v_item_loja.item_id;
    if not found then
      insert into public.inventarios (personagem_id, item_id, quantidade, updated_at)
      values (p_personagem_id, v_item_loja.item_id, v_linha.quantidade, now());
    end if;
  end loop;

  v_novo_saldo := v_saldo - v_total;
  v_carteira := v_carteira || jsonb_build_object('po', v_novo_saldo);
  v_dados := jsonb_set(v_dados, '{carteira}', v_carteira, true);
  update public.personagens set dados = v_dados where id = p_personagem_id;

  insert into public.campanha_compras (
    campanha_id, personagem_id, user_id, request_id, itens, saldo_po, total_gasto
  ) values (
    v_campanha_id, p_personagem_id, v_usuario_id, v_request_id, p_itens, v_novo_saldo, v_total
  );
  return jsonb_build_object(
    'personagem_id', p_personagem_id,
    'saldo_po', v_novo_saldo,
    'total_gasto', v_total
  );
end;
$$;

revoke all on function public.registrar_compra_carrinho(uuid, jsonb, uuid) from public;
grant execute on function public.registrar_compra_carrinho(uuid, jsonb, uuid) to authenticated;

notify pgrst, 'reload schema';
